const assert=require('node:assert/strict');
const catalog=require('../miniprogram/utils/catalog'),backup=require('../miniprogram/utils/backup');
const updates=require('../miniprogram/data/course-updates');
const original=updates.courses,selectors=updates.replace;updates.courses=[];updates.replace=[];
const row={id:'lab_demo',name:'示例实验',weekday:2,start:9,end:11,first:5,last:5,parity:'all',date:'2026-10-13',timeStart:'18:30',timeEnd:'21:30',periodLabel:'实验 · 4学时',detail:'示例实验项目'};
const normalized=catalog.normalize({courses:[row]});
assert.equal(normalized.courses[0].date,row.date);
assert.equal(normalized.courses[0].timeEnd,'21:30');
assert.equal(backup.decode(backup.encode({overrides:{},changes:{},timetable:normalized})).timetable.courses[0].detail,row.detail);
assert.throws(()=>catalog.normalize({courses:[{...row,timeEnd:'18:00'}]}));
assert.throws(()=>catalog.normalize({courses:[{...row,timeStart:['18:30']}]}));
assert.throws(()=>catalog.normalize({courses:[{...row,date:'2026-02-30'}]}));
global.wx={getStorageSync:()=>({timetable:normalized})};
const {daySchedule,nextCourse}=require('../miniprogram/utils/schedule');
assert.equal(daySchedule(row.date).courses[0].time,'18:30—21:30');
assert.equal(daySchedule(row.date).courses[0].period,row.periodLabel);
assert.equal(daySchedule('2026-10-17',{'2026-10-17':{type:'makeup',source:row.date}}).courses.length,0);
assert.equal(daySchedule(row.date,{[row.date]:{type:'makeup',source:'2026-10-12'}}).courses.length,1);
assert.equal(daySchedule(row.date,{[row.date]:{type:'off'}}).courses.length,0);
assert.equal(nextCourse(row.date,'21:10').state,'current');
assert.equal(nextCourse(row.date,'21:30').state,'done');
const moved=daySchedule('2026-10-14',{}, {[row.date+'|'+row.id]:{source:row.date,courseId:row.id,type:'move',target:'2026-10-14',start:1,end:2}}).courses[0];
assert.equal(moved.time,'08:00—09:35');
const extra={...row,id:'earlier',start:10,timeStart:'18:00',timeEnd:'18:20'};
global.wx.getStorageSync=()=>({timetable:{courses:[row,extra],pending:[]}});
assert.equal(nextCourse(row.date,'17:00').courses[0].id,'earlier');
updates.courses=[row];updates.replace=[{name:'旧示例实验',weekday:2,parity:'odd'}];
global.wx.getStorageSync=()=>({timetable:{courses:[{...row,id:'old',name:'旧示例实验',parity:'odd'},{...row,id:'keep',name:'保留课程',weekday:1}],pending:[]}});
assert.deepEqual(catalog.get().courses.map(c=>c.id),['keep','lab_demo']);
const legacy={courses:[{...row,id:'old',name:'旧示例实验'}]};
const change={source:row.date,courseId:row.id,type:'cancel'};
assert(backup.normalize({overrides:{},changes:{[row.date+'|'+row.id]:change},timetable:legacy}).changes[row.date+'|'+row.id]);
updates.courses=original;updates.replace=selectors;
console.log('指定日期与准确时间通过：备份保留、倒计时到21:30、补课不复制固定实验、移课重算时间、定向替换不影响其他课程');
