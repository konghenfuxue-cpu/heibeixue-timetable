assert(daySchedule('2026-09-17').courses.some(c=>c.name==='示例课程3'));
assert(daySchedule('2026-09-24').courses.some(c=>c.name==='示例课程5'));
assert(daySchedule('2026-09-30').courses.filter(c=>c.conflict).length===3);
assert.equal(daySchedule('2027-01-09').courses.length,0);
assert.equal(daySchedule('2026-09-13').courses.length,0);
assert.equal(daySchedule('2026-10-23').notice,'秋季运动会，请确认停课安排');
assert.equal(daySchedule('2026-10-07',{'2026-10-07':{type:'makeup',source:'2026-10-05'}}).courses.length,4);
assert.equal(daySchedule('2026-10-08',{'2026-10-08':{type:'off',note:'临时停课'}}).courses.length,0);
assert.throws(()=>daySchedule('2026-02-30'));
assert.throws(()=>daySchedule('2026-10-08',{'2026-10-08':{type:'makeup',source:'bad'}}));
const {nextCourse,validateChange,weekDates,colorFor,gridGroups}=require('../miniprogram/utils/schedule');
const source='2026-09-21';
const rule={source,courseId:'c0',type:'move',target:'2026-10-08',start:7,end:8,room:'示例教室101'};
validateChange(rule,{});
const changes={[source+'|c0']:rule};
assert(!daySchedule(source,{},changes).courses.some(c=>c.id==='c0'));
const moved=daySchedule('2026-10-08',{},changes).courses.find(c=>c.id==='c0');
assert.equal(moved.time,'15:25—17:00');
assert.equal(moved.room,'示例教室101');
assert.equal(moved.origin,source);
assert.equal(daySchedule(source,{},{}).courses.length,3);
assert.equal(daySchedule(source,{}, {[source+'|c0']:{source,courseId:'c0',type:'cancel'}}).courses.length,2);
assert.equal(daySchedule('2026-10-08',{'2026-10-08':{type:'off'}},changes).courses.length,0);
assert.throws(()=>validateChange({...rule,start:9,end:7},{}));
assert.throws(()=>validateChange({...rule,start:0},{}));
assert.throws(()=>validateChange({...rule,target:'2027-01-09'},{}));
assert.throws(()=>validateChange({...rule,source:'2026-10-07'},{}));
const holidayMove={...rule,target:'2026-10-07'};
assert.equal(daySchedule('2026-10-07',{}, {[source+'|c0']:holidayMove}).courses.length,1);
assert.equal(nextCourse('2026-10-08','07:30').minutes,30);
assert.equal(nextCourse('2026-10-08','08:00').state,'current');
assert.equal(nextCourse('2026-10-08','09:35').state,'next');
assert.equal(nextCourse('2026-10-08','21:00').state,'done');
assert.equal(nextCourse('2026-10-07','09:00').state,'empty');
assert.equal(nextCourse('2026-09-30','19:00').courses.length,3);
assert.equal(weekDates('2026-10-07')[0].date,'2026-10-05');
assert.equal(weekDates('2026-10-11')[6].date,'2026-10-11');
assert.equal(daySchedule('2026-09-14').courses.find(c=>c.id==='c0').color,daySchedule('2026-09-16').courses.find(c=>c.id==='c8').color);
assert.equal(daySchedule('2026-09-28',{}, {[source+'|c0']:{source,courseId:'c0',type:'cancel'}}).courses.length,4);
const roomChange={...rule,target:source,start:1,end:2,room:'新教室'};
assert.equal(daySchedule(source,{}, {[source+'|c0']:roomChange}).courses.filter(c=>c.id==='c0').length,1);
assert.equal(daySchedule(source,{}, {[source+'|c0']:roomChange}).courses.find(c=>c.id==='c0').room,'新教室');
