assert.equal(daySchedule('2026-09-20').week, 2);
assert.equal(daySchedule('2026-10-10').weekday, 2);
assert.equal(daySchedule('2026-10-10').week, 4);
assert.equal(daySchedule('2026-10-10').notice, '补第4周星期二课程（双周二）');
const builtinCourses=require('../miniprogram/data/courses').courses;
assert.deepEqual(daySchedule('2026-10-10').courses.map(c=>c.id).sort(),builtinCourses.filter(c=>c.weekday===2&&c.first<=4&&c.last>=4&&c.parity!=='odd').map(c=>c.id).sort());
