const assert = require('node:assert/strict');
const {daySchedule, slots} = require('../miniprogram/utils/schedule');
assert.equal(daySchedule('2026-09-14').week, 1);
assert.equal(daySchedule('2026-10-07').courses.length, 0);
assert.equal(daySchedule('2026-10-07').notice, '国庆放假');
