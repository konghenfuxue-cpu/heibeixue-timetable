const duplicates=daySchedule('2026-09-28',{}, {[source+'|c0']:sameCourse}).courses.filter(c=>c.id==='c0');
assert.equal(duplicates.length,2);
assert.notEqual(duplicates[0].uid,duplicates[1].uid);
assert(duplicates.every(c=>c.conflict));
